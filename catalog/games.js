// === Валидатор (dev-only) ===
(function validate() {
  if (!window.GAMES || !window.GAMES.length) {
    console.warn("[games.js] пустой каталог");
    return;
  }
  const genres = new Set(), names = new Set();
  window.GAMES.forEach((g, i) => {
    const err = (m) => console.warn(`[games.js] #${i} «${g.name || "?"}»: ${m}`);
    if (typeof g.name !== "string" || !g.name) err("нет name");
    if (typeof g.difficulty !== "number" || g.difficulty < 0.5 || g.difficulty > 5 || (g.difficulty * 2) % 1 !== 0)
      err(`difficulty=${g.difficulty}`);
    if (!Number.isInteger(g.minPlayers) || !Number.isInteger(g.maxPlayers) || g.minPlayers > g.maxPlayers)
      err(`игроки ${g.minPlayers}–${g.maxPlayers}`);
    if (typeof g.special !== "boolean") err("special не boolean");
    if (!Array.isArray(g.expansions)) err("expansions не массив");
    if (typeof g.description !== "string") err("description не строка");
    if (names.has(g.name)) err("дубликат названия");
    names.add(g.name);
    genres.add(g.genre || "");
  });
  console.info(`[games.js] загружено ${window.GAMES.length} игр, жанров: ${[...genres].filter(Boolean).length}`);
})();
